#!/usr/bin/env python3
"""Generate C class and virtual method table headers from build/method_tables.json
and build/subsystem_map.json.

Produces:
- src/recovered/generated/classes_vtables.h
"""

import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generate_headers():
    mt = json.load(open(ROOT / "build/method_tables.json"))
    submap = json.load(open(ROOT / "build/subsystem_map.json"))
    decomp = json.load(open(ROOT / "build/decomp/decomp_index.json"))

    vt_meta = {v["table"]: v for v in submap["vtables"]}
    func_meta = {f["entry"]: f for f in decomp["functions"]}

    # Find allocation sizes from constructors
    alloc_sizes = defaultdict(set)
    for c in mt["constructors"]:
        if c["kind"] == "constructor" and c.get("alloc"):
            alloc_sizes[c["final"]].add(c["alloc"])

    out_dir = ROOT / "src/recovered/generated"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "classes_vtables.h"

    lines = [
        "/* Auto-generated by tools/generate_class_headers.py",
        " * Source: build/method_tables.json & build/subsystem_map.json",
        " * Covers all 142 C++ virtual method tables in original/BLIZZARD.EXE.",
        " */",
        "#ifndef SB_GENERATED_CLASSES_VTABLES_H",
        "#define SB_GENERATED_CLASSES_VTABLES_H",
        "",
        "#include <stdint.h>",
        "",
        "#if defined(__WATCOMC__) && defined(_M_I86)",
        "#define SB_FAR __far",
        "#define SB_PASCAL __pascal",
        "#else",
        "#define SB_FAR",
        "#define SB_PASCAL",
        "#endif",
        "",
        "typedef void (SB_FAR SB_PASCAL *SBVtableMethodPtr)(void);",
        "",
    ]

    # Forward declare all 142 class structs and vtable structs
    lines.append("/* Forward declarations for 142 recovered classes */")
    for t in mt["tables"]:
        t_addr = t["table"]
        cname = vt_meta[t_addr]["class_name"]
        lines.append(f"typedef struct {cname} {cname};")
        lines.append(f"typedef struct {cname}_Vtable {cname}_Vtable;")
    lines.append("")

    # Emit each vtable struct and object skeleton
    for t in mt["tables"]:
        t_addr = t["table"]
        meta = vt_meta[t_addr]
        cname = meta["class_name"]
        subsys = meta["subsystem"]
        role = meta["role"]
        parents = " -> ".join(t["parents"]) if t["parents"] else "(root)"
        sizes = sorted(alloc_sizes.get(t_addr, []))
        size_comment = ", ".join(f"0x{s:x} ({s} B)" for s in sizes) if sizes else "dynamic / base"

        lines.append("/* ==========================================================================")
        lines.append(f" * Class:      {cname}")
        lines.append(f" * Vtable:     {t_addr} ({t['slots']} slots, {t['slots'] * 4} bytes)")
        lines.append(f" * Parents:    {parents}")
        lines.append(f" * Alloc Size: {size_comment}")
        lines.append(f" * Subsystem:  {subsys}")
        lines.append(f" * Role:       {role}")
        lines.append(" * ========================================================================== */")
        lines.append(f"struct {cname}_Vtable {{")

        override_map = {int(s, 16): (fn, prev) for s, fn, prev in t["overrides"]}
        for idx, cell in enumerate(t["cells"]):
            slot_off = idx * 4
            fn_tag = cell.replace(":", "_")
            fm = func_meta.get(cell)
            purge_str = f"RETF {fm['purge']}" if fm and fm["purge"] >= 0 else "unbounded"
            if slot_off in override_map:
                _, prev = override_map[slot_off]
                origin = "new" if prev == "new" else f"overrides {prev}"
            else:
                origin = "inherited"
            lines.append(
                f"    SBVtableMethodPtr slot_{slot_off:03x}_{fn_tag}; /* +0x{slot_off:02x} -> {cell} ({purge_str}, {origin}) */"
            )
        lines.append("};")
        lines.append("")

        min_bytes = max(sizes) if sizes else 4
        payload_bytes = max(0, min_bytes - 4)
        lines.append(f"struct {cname} {{")
        lines.append(f"    const {cname}_Vtable SB_FAR *vtable; /* +0x00..+0x03 (far vtable ptr -> {t_addr}) */")
        if payload_bytes > 0:
            lines.append(f"    uint8_t fields_04[0x{payload_bytes:x}]; /* +0x04..+0x{min_bytes - 1:02x} */")
        lines.append("};")
        lines.append("")

    lines.append("#endif /* SB_GENERATED_CLASSES_VTABLES_H */")
    lines.append("")

    out_path.write_text("\n".join(lines))
    print(f"Generated {out_path} ({len(lines)} lines, {len(mt['tables'])} classes)")


if __name__ == "__main__":
    generate_headers()
